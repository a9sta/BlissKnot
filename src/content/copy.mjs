/** 매듭이 몇이냐를 말로 — 숫자만 적으면 감이 오지 않는다. */
export function knotWord(n) {
  if (n === 0) return '어느 점에서도 셋이 만나지 않는';
  if (n <= 2) return '매듭이 드문';
  if (n <= 4) return '매듭이 적은 편인';
  if (n <= 6) return '매듭이 보통인';
  if (n <= 9) return '매듭이 잦은';
  return '매듭이 유난히 많은';
}
/** 가장 큰 매듭이 몇 겹인지 */
export function topWord(k) {
  if (k >= 5) return '다섯 자리가 한 점을 함께 쥔 매듭이 있습니다';
  if (k === 4) return '네 자리가 한 점에서 만나는 매듭이 있습니다';
  if (k === 3) return '가장 큰 매듭도 세 자리가 만나는 자리입니다';
  return '셋이 모이는 점이 잡히지 않습니다';
}
/** 넓이를 걸음으로 */
export function walkWord(a) {
  if (a < 1) return '테두리를 따라 걸어도 한 바퀴가 금세 돕니다';
  if (a < 3) return '천천히 걸어 건너편까지 갈 만합니다';
  if (a < 10) return '걸어 건너기엔 버거워 차를 타게 됩니다';
  if (a < 30) return '같은 이름 안에서도 차로 움직이게 됩니다';
  return '이 끝에서 저 끝까지 가는 것만으로 일이 됩니다';
}

